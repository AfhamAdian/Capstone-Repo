def group(d,x,y,w,h,label,color,fill):
    d.d.rounded_rectangle((x*2,y*2,(x+w)*2,(y+h)*2),radius=32,fill=fill,outline='#d8e1ea',width=2)
    d.svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="16" fill="{fill}" stroke="#d8e1ea"/>')
    d.text(x+w/2,y+30,label,19,color,True)

def store(d,x,y,w,title,detail):
    d.box(x,y,w,100,title,detail,fill='#eaf0f6',color='#8293a5')
    d.line([(x+14,y+10),(x+w-14,y+10)],'#b5c3d1',2)
    d.line([(x+14,y+90),(x+w-14,y+90)],'#b5c3d1',2)

def note(d,t):d.text(d.w/2,d.h-35,t,18,MUTED)

